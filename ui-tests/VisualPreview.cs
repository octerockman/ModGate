        var catalog = new ProfileCatalog
        {
            Active = "offline", OfflineMods = installed,
            Servers = new()
            {
                new SavedProfile { Slot = "server-1", Name = "The Northern Realms", ServerKey = new string('a', 64), ServerPolicy = policy, Mods = policy.Mods,
                    ConfigBindings = new() { new() { Guid = camping.Guid, Files = new() { "Camping.cfg" } }, new() { Guid = map.Guid, Files = new() { "Cartography.cfg" } }, new() { Guid = portal.Guid, Files = new() { "TeleportEverything.cfg" } } } },
