// Replays production Prompt.Draw calls. This is a layout/style diagnostic, not a Unity screenshot:
// Unity's text metrics, GUILayout intrinsic sizing, hover state and game backdrop are approximated.
internal static class VisualPreview
{
    private const BindingFlags Private = BindingFlags.Instance | BindingFlags.NonPublic;
    internal static void Set(Prompt prompt, string name, object? value) => typeof(Prompt).GetField(name, Private)!.SetValue(prompt, value);
    internal static object? Call(Prompt prompt, string name, params object[] values) => typeof(Prompt).GetMethod(name, Private)!.Invoke(prompt, values);
    internal static void Export(string[] args)
    {
        var index = Array.IndexOf(args, "--visual-preview");
        var output = Path.GetFullPath(index + 1 < args.Length && !args[index + 1].StartsWith("--", StringComparison.Ordinal) ? args[index + 1] : "artifacts/ui-preview");
        Directory.CreateDirectory(output);
        foreach (var surface in new[] { "mods", "dependencies", "profiles", "mod-details", "mod-detail", "configs", "server-configs", "server-health", "server-health-narrow", "server-health-history", "download", "prepare", "success", "success-narrow", "creators", "creators-narrow", "creator-popup", "creator-popup-narrow" })
        {
            using var fixture = surface.EndsWith("-narrow", StringComparison.Ordinal) ? Create(surface, 640, 900) : Create(surface);
            Capture(fixture.Prompt);
            var commands = DrawCapture.Commands.ToArray();
            DrawCapture.EncodeTextures();
            var metadata = new
            {
                schema = 1, surface, viewport = new { width = Screen.width, height = Screen.height },
                source = "Production src/ValheimModGate/Prompt*.cs: Prompt.Draw()",
                limitations = "Fixed Rects, texture pixels, styles and clipping are captured from production. Intrinsic GUILayout sizing and native browser font metrics approximate Unity. The flat backdrop is a preview stage, not the game.",
                commands
            };
            var options = new JsonSerializerOptions { WriteIndented = true, IncludeFields = true };
            options.Converters.Add(new JsonStringEnumConverter());
            File.WriteAllText(Path.Combine(output, surface + ".json"), JsonSerializer.Serialize(metadata, options));
            var svg = Svg(commands);
            File.WriteAllText(Path.Combine(output, surface + ".svg"), svg);
            File.WriteAllText(Path.Combine(output, surface + ".html"), "<!doctype html><meta charset=\"utf-8\"><title>ModGate production draw replay — " + surface + "</title><style>html,body{margin:0;width:100%;height:100%;background:#0b1412;overflow:hidden}svg{display:block}</style>" + svg);
            Console.WriteLine("Production draw replay: " + Path.Combine(output, surface + ".html") + " (" + commands.Length + " commands)");
        }
        File.WriteAllText(Path.Combine(output, "README.txt"), "Generated by --visual-preview from actual production Prompt.Draw calls. Each JSON file records its viewport dimensions.\nJSON is the captured draw list; SVG/HTML replay the same list. Fixed Rect coordinates, captured colors, generated texture pixels, 9-slice borders and clip bounds are preserved. Unity's font rasterization and intrinsic GUILayout sizing are approximated; this does not replace an in-game screenshot. Fixture data is synthetic and all fixture files are isolated under the operating-system temporary directory.\n");
    }

    internal sealed class Fixture : IDisposable
    {
        internal Prompt Prompt = null!;
        internal string Root = "";
        public void Dispose()
        {
            Prompt.Dispose(); DrawCapture.Enabled = false;
            try { if (Directory.Exists(Root)) Directory.Delete(Root, true); } catch (IOException) { }
        }
    }
    internal static Fixture Create(string surface, int width = 1280, int height = 1000)
    {
