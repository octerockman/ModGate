    internal static void Capture(Prompt prompt)
    {
        GUI.Buttons.Clear(); GUILayout.Toggles.Clear(); GUILayout.Labels.Clear();
        DrawCapture.Clear(); DrawCapture.Enabled = true;
        try { prompt.Draw(); } finally { DrawCapture.Enabled = false; }
    }

    private static string N(float value) => value.ToString("0.###", CultureInfo.InvariantCulture);
    private static string Esc(string value) => WebUtility.HtmlEncode(value);
    private static string Rgb(Color value) => "rgb(" + (int)Math.Round(value.r * 255) + "," + (int)Math.Round(value.g * 255) + "," + (int)Math.Round(value.b * 255) + ")";
    private static string Svg(IReadOnlyList<DrawCommand> commands)
    {
        var result = new StringBuilder("<svg xmlns=\"http://www.w3.org/2000/svg\" xmlns:xhtml=\"http://www.w3.org/1999/xhtml\" width=\"").Append(Screen.width).Append("\" height=\"").Append(Screen.height).Append("\" viewBox=\"0 0 ").Append(Screen.width).Append(' ').Append(Screen.height).Append("\"><rect width=\"100%\" height=\"100%\" fill=\"#0b1412\"/>");
        for (var i = 0; i < commands.Count; i++)
        {
            var c = commands[i]; var r = c.Area; var clip = c.Clip;
            if (r.width <= 0 || r.height <= 0 || clip.width <= 0 || clip.height <= 0) continue;
            result.Append("<defs><clipPath id=\"c").Append(i).Append("\"><rect x=\"").Append(N(clip.x)).Append("\" y=\"").Append(N(clip.y)).Append("\" width=\"").Append(N(clip.width)).Append("\" height=\"").Append(N(clip.height)).Append("\"/></clipPath></defs><g clip-path=\"url(#c").Append(i).Append(")\">");
            if (c.TexturePng != null) Texture(result, c);
            if (c.Text.Length > 0 && c.TextColor.a > 0)
            {
                var align = (int)c.Alignment % 3; var vertical = (int)c.Alignment / 3;
                var color = new Color(c.TextColor.r * c.Tint.r, c.TextColor.g * c.Tint.g, c.TextColor.b * c.Tint.b, c.TextColor.a * c.Tint.a);
                var font = c.FontStyle == FontStyle.Bold || c.FontStyle == FontStyle.BoldAndItalic ? "700" : "400";
                var italic = c.FontStyle == FontStyle.Italic || c.FontStyle == FontStyle.BoldAndItalic ? "italic" : "normal";
                result.Append("<foreignObject x=\"").Append(N(r.x + c.ContentOffset.x)).Append("\" y=\"").Append(N(r.y + c.ContentOffset.y)).Append("\" width=\"").Append(N(r.width)).Append("\" height=\"").Append(N(r.height)).Append("\"><xhtml:div style=\"box-sizing:border-box;width:100%;height:100%;overflow:hidden;display:flex;flex-direction:column;justify-content:").Append(vertical == 0 ? "flex-start" : vertical == 1 ? "center" : "flex-end").Append(";padding:").Append(c.Padding[2]).Append("px ").Append(c.Padding[1]).Append("px ").Append(c.Padding[3]).Append("px ").Append(c.Padding[0]).Append("px;font-family:&quot;").Append(Esc(c.Font)).Append("&quot;,Segoe UI,Arial,sans-serif;font-size:").Append(c.FontSize).Append("px;font-weight:").Append(font).Append(";font-style:").Append(italic).Append(";line-height:1.25;color:").Append(Rgb(color)).Append(";opacity:").Append(N(color.a)).Append(";text-align:").Append(align == 0 ? "left" : align == 1 ? "center" : "right").Append(";white-space:").Append(c.Wrap ? "pre-wrap;overflow-wrap:anywhere" : "pre").Append("\"><xhtml:div>").Append(Esc(c.Text)).Append("</xhtml:div></xhtml:div></foreignObject>");
            }
            result.Append("</g>");
        }
        return result.Append("</svg>").ToString();
    }
    private static void Texture(StringBuilder target, DrawCommand c)
    {
        var r = c.Area;
        var b = c.Border;
        if (b.All(v => v == 0) || c.TextureWidth <= b[0] + b[1] || c.TextureHeight <= b[2] + b[3])
        {
            target.Append("<image x=\"").Append(N(r.x)).Append("\" y=\"").Append(N(r.y)).Append("\" width=\"").Append(N(r.width)).Append("\" height=\"").Append(N(r.height)).Append("\" preserveAspectRatio=\"none\" opacity=\"").Append(N(c.Tint.a)).Append("\" href=\"data:image/png;base64,").Append(c.TexturePng).Append("\"/>"); return;
        }
        var left = Math.Min(b[0], r.width / 2); var right = Math.Min(b[1], r.width / 2);
        var top = Math.Min(b[2], r.height / 2); var bottom = Math.Min(b[3], r.height / 2);
        var dx = new[] { r.x, r.x + left, r.xMax - right, r.xMax };
        var dy = new[] { r.y, r.y + top, r.yMax - bottom, r.yMax };
        var sx = new[] { 0, b[0], c.TextureWidth - b[1], c.TextureWidth };
        var sy = new[] { 0, b[2], c.TextureHeight - b[3], c.TextureHeight };
        for (var y = 0; y < 3; y++) for (var x = 0; x < 3; x++)
        {
            if (dx[x + 1] <= dx[x] || dy[y + 1] <= dy[y]) continue;
            target.Append("<svg x=\"").Append(N(dx[x])).Append("\" y=\"").Append(N(dy[y])).Append("\" width=\"").Append(N(dx[x + 1] - dx[x])).Append("\" height=\"").Append(N(dy[y + 1] - dy[y])).Append("\" viewBox=\"").Append(sx[x]).Append(' ').Append(sy[y]).Append(' ').Append(sx[x + 1] - sx[x]).Append(' ').Append(sy[y + 1] - sy[y]).Append("\" preserveAspectRatio=\"none\" overflow=\"hidden\"><image width=\"").Append(c.TextureWidth).Append("\" height=\"").Append(c.TextureHeight).Append("\" href=\"data:image/png;base64,").Append(c.TexturePng).Append("\" opacity=\"").Append(N(c.Tint.a)).Append("\"/></svg>");
        }
    }
