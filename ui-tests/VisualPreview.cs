        Screen.width = width; Screen.height = height; ZNet.instance = null;
        GUI.enabled = true; GUI.color = Color.white; GUI.backgroundColor = Color.white; GUI.contentColor = Color.white;
        GUI.Buttons.Clear(); GUILayout.Toggles.Clear(); GUILayout.Labels.Clear(); GUI.Click = null; GUILayout.ThrowContent = false;
        GUILayout.ScrollDepth = 0; GUILayout.AreaDepth = 0; ZInput.instance = new object(); ZInput.Pressed.Clear(); ZInput.Released.Clear(); ZInput.Held.Clear();
        Event.current = new Event { type = EventType.Repaint, mousePosition = new(-100, -100) };
        UnityEngine.EventSystems.EventSystem.current = null;
